# Builds drv_check_spv.h: the driver checks' shaders (GLSL -> SPIR-V 1.0 with glslc; the float check's min becomes NMin through spirv-dis / spirv-as)
set -e
T=$HOME/android-ndk-r27c/shader-tools/linux-x86_64; X=$HOME/spvt/x/usr/bin
D=$(cd "$(dirname "$0")" && pwd); O=$D/drv_check_spv.h; W=$(mktemp -d)
cat > $W/full.vert <<'G'
#version 450
// a triangle over the whole target; its colour from push constants at offset 64 (where draw parameters go on a device without them)
layout(push_constant) uniform P { layout(offset = 64) vec4 c; } pc;
layout(location = 0) out vec4 col;
void main() { vec2 p = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2); gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0); col = pc.c; }
G
cat > $W/col.frag <<'G'
#version 450
layout(location = 0) in vec4 col;
layout(location = 0) out vec4 o;
void main() { o = col; }
G
cat > $W/dual.frag <<'G'
#version 450
// dual-source blending: output 0 black, output 1 (index 1) green; blended dst * SRC1_COLOR over a white target gives green
layout(location = 0, index = 0) out vec4 o0;
layout(location = 0, index = 1) out vec4 o1;
void main() { o0 = vec4(0.0, 0.0, 0.0, 1.0); o1 = vec4(0.0, 1.0, 0.0, 1.0); }
G
cat > $W/flt.frag <<'G'
#version 450
// float specials as Maxwell has them, from push constants so nothing is folded at compile time: a = NaN, b = 0.5, d = +inf
//   red: the plain min(NaN, 0.5) is 0.5 (Maxwell drops a NaN operand: no rewrite needed), green: max(NaN, 0.5) is 0.5 through NMax (the rewrite spv_nan_minmax makes;
//   max becomes NMax below), blue: isinf(+inf) and isnan(NaN)
layout(push_constant) uniform P { float a, b, d; } pc;
layout(location = 0) out vec4 o;
void main() { o = vec4(min(pc.a, pc.b) == 0.5 ? 1.0 : 0.0, max(pc.a, pc.b) == 0.5 ? 1.0 : 0.0, isinf(pc.d) && isnan(pc.a) ? 1.0 : 0.0, 1.0); }
G
for s in full.vert col.frag dual.frag flt.frag; do $T/glslc --target-env=vulkan1.0 -O0 -o $W/$s.spv $W/$s; done
$X/spirv-dis --raw-id $W/flt.frag.spv | sed 's/ FMax / NMax /' > $W/flt.asm; grep -q NMax $W/flt.asm; grep -q FMin $W/flt.asm
$X/spirv-as --target-env vulkan1.0 -o $W/flt.frag.spv $W/flt.asm
for s in full.vert col.frag dual.frag flt.frag; do $X/spirv-val --target-env vulkan1.0 $W/$s.spv; done
python3 - $W $O <<'PY'
import sys, struct
w, o = sys.argv[1], sys.argv[2]
out = ['// Generated by the driver checks\' gen.sh (glslc, NDK r27c; spirv-as for the float check): drv_check.h\'s shaders, SPIR-V 1.0']
for s, n in (('full.vert', 'dck_vs'), ('col.frag', 'dck_fs_col'), ('dual.frag', 'dck_fs_dual'), ('flt.frag', 'dck_fs_flt')):
    b = open(f'{w}/{s}.spv', 'rb').read(); ws = struct.unpack(f'<{len(b)//4}I', b)
    out.append(f'static const uint32_t {n}[] = {{' + ','.join(f'0x{x:08x}' for x in ws) + '};')
open(o, 'w').write('\n'.join(out) + '\n')
PY
echo wrote $O; rm -rf $W
